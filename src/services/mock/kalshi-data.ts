export function getMockKalshiBetsResponse(): KalshiBetsResponse {
  const portfolio = selectKalshiPortfolio(mockKalshiBets);
  const props = mockKalshiBets.filter((b) => b.betType === "player_prop").length;
  const moneylines = mockKalshiBets.filter((b) => b.betType === "moneyline").length;
  return {
    bets: portfolio.bets,
    updatedAt: new Date().toISOString(),
    source: "kalshi",
    propsScored: props,
    moneylinesScored: moneylines,
    filteredCount: portfolio.filteredCount,
    survivorCount: portfolio.survivorCount,
    pickHitRate: mockPickHitRate(),
  };
}
