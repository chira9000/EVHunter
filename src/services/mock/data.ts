function movement(base: number): BetOpportunity["lineMovement"] {
  const now = Date.now();
  return Array.from({ length: 12 }, (_, i) => {
    const drift = Math.floor(Math.random() * 8) - 4;
    const odds = base + drift * (i % 3 === 0 ? 1 : 0);
    return {
      timestamp: new Date(now - (12 - i) * 3600000).toISOString(),
      americanOdds: odds,
      impliedProb: odds > 0 ? 100 / (odds + 100) : Math.abs(odds) / (Math.abs(odds) + 100),
    };
  });
}

